import { describe, expect, it } from "vitest";
import { colMajor, wbMatrix, type Mat3 } from "../src/lib/render/wb";

const near = (a: Mat3, b: number[][], tol = 1e-5) => {
  for (let r = 0; r < 3; r++) for (let c = 0; c < 3; c++) expect(Math.abs(a[r]![c]! - b[r]![c]!), `[${r}][${c}] ${a[r]![c]} vs ${b[r]![c]}`).toBeLessThan(tol);
};

describe("섹션 15.2-2 화이트밸런스 (행 우선)", () => {
  it("(0,0) → 단위행렬", () => near(wbMatrix(0, 0), [[1, 0, 0], [0, 1, 0], [0, 0, 1]], 1e-6));
  it("(50,0)", () => near(wbMatrix(50, 0), [[1.057763, 0.078484, 0.012776], [-0.003743, 0.986666, 0.004438], [-0.005792, -0.020475, 0.776022]]));
  it("(−50,0)", () => near(wbMatrix(-50, 0), [[0.942534, -0.088858, -0.016324], [0.004207, 1.022824, -0.006061], [0.00759, 0.02742, 1.308883]]));
  it("(0,50)", () => near(wbMatrix(0, 50), [[1.042517, 0.090213, -0.00052], [-0.004555, 0.959117, -0.003382], [0.001786, 0.011141, 1.106101]]));
  it("(30,−20)", () => near(wbMatrix(30, -20), [[1.015504, 0.007934, 0.007387], [-0.000277, 1.00899, 0.003849], [-0.003971, -0.01597, 0.831719]]));
  it("colMajor 순서", () => {
    expect(Array.from(colMajor([[1, 2, 3], [4, 5, 6], [7, 8, 9]]))).toEqual([1, 4, 7, 2, 5, 8, 3, 6, 9]);
  });
});
