import { describe, expect, it } from "vitest";
import { colMajor, wbMatrix, type Mat3 } from "../src/lib/render/wb";

const near = (a: Mat3, b: number[][], tol = 1e-5) => {
  for (let r = 0; r < 3; r++) for (let c = 0; c < 3; c++) expect(Math.abs(a[r]![c]! - b[r]![c]!), `[${r}][${c}] ${a[r]![c]} vs ${b[r]![c]}`).toBeLessThan(tol);
};

describe("섹션 15.2-2 화이트밸런스 (행 우선)", () => {
  it("(0,0) → 단위행렬", () => near(wbMatrix(0, 0), [[1, 0, 0], [0, 1, 0], [0, 0, 1]], 1e-6));
  it("(50,0)", () => near(wbMatrix(50, 0), [[1.0704, 0.094276, 0.015198], [-0.004499, 0.98498, 0.005247], [-0.006875, -0.024255, 0.73576]]));
  it("(−50,0)", () => near(wbMatrix(-50, 0), [[0.875137, -0.208012, -0.042711], [0.009775, 1.062595, -0.016698], [0.020267, 0.074446, 1.84733]]));
  it("(0,50)", () => near(wbMatrix(0, 50), [[1.108611, 0.220556, -0.002849], [-0.011163, 0.904537, -0.009148], [0.005243, 0.030833, 1.304237]]));
  it("(30,−20)", () => near(wbMatrix(30, -20), [[0.993467, -0.045566, 0.007646], [0.002423, 1.036406, 0.005827], [-0.005003, -0.022464, 0.773225]]));
  it("colMajor 순서", () => {
    expect(Array.from(colMajor([[1, 2, 3], [4, 5, 6], [7, 8, 9]]))).toEqual([1, 4, 7, 2, 5, 8, 3, 6, 9]);
  });
});
