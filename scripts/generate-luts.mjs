// FSE-v2 3D LUT 생성기 — docs/COLOR_SCIENCE.md §5~§7.
// 사용: node scripts/generate-luts.mjs [--check]
// 엔진 로직은 src/lib/color/fse/*.mjs 에서 import 한다(복제 금지). 출력에 타임스탬프·무작위값 없음.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LUT_SIZE, REF_TONE, SHAPER_C, SHAPER_XMAX } from "../src/lib/color/fse/constants.mjs";
import { renderPoint, shaperDec, srgbDec, tone, toneCoeffs } from "../src/lib/color/fse/engine.mjs";
import { FILM_SIMS } from "../src/lib/color/fse/film-params.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "public", "luts");
const CHECK = process.argv.includes("--check");
const N = LUT_SIZE;

/** @param {number[]} v */
const luma709 = (v) => 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2];
/** @param {string | Uint8Array} buf */
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

/** @param {string} msg */
function fail(msg) {
  console.error(`[generate-luts] 검증 실패: ${msg}`);
  process.exit(1);
}

// ---- 2. 생성 전 검증 ----
function validate() {
  /** @type {string[]} */
  const errors = [];
  if (FILM_SIMS.length !== 32) errors.push(`FILM_SIMS.length = ${FILM_SIMS.length} (기대 32)`);
  const fuji = FILM_SIMS.filter((p) => p.brand === "fujifilm").length;
  const ricoh = FILM_SIMS.filter((p) => p.brand === "ricoh").length;
  if (fuji !== 20) errors.push(`fujifilm ${fuji}개 (기대 20)`);
  if (ricoh !== 12) errors.push(`ricoh ${ricoh}개 (기대 12)`);
  const ids = new Set();
  for (const p of FILM_SIMS) {
    if (ids.has(p.id)) errors.push(`id 중복: ${p.id}`);
    ids.add(p.id);
  }
  for (const P of FILM_SIMS) {
    const k = toneCoeffs(P.tone);
    if (!(k.b > 0)) errors.push(`${P.id}: b = ${k.b} ≤ 0`);
    if (!(k.c > 0)) errors.push(`${P.id}: c = ${k.c} ≤ 0`);
    if (!(k.d <= 1)) errors.push(`${P.id}: d = ${k.d} > 1`);
    let prev = -Infinity;
    for (let i = 0; i <= 4000; i++) {
      const t = tone((k.hdrMax * i) / 4000, k);
      if (t < prev) {
        errors.push(`${P.id}: tone 단조 위반 (i=${i})`);
        break;
      }
      prev = t;
    }
    if (P.mono) {
      const m = P.mixer ?? [];
      if (m.length !== 3 || m.some((v) => !(v >= 0))) errors.push(`${P.id}: mixer 원소가 3개가 아니거나 음수`);
      const s = m.reduce((acc, v) => acc + v, 0);
      if (Math.abs(s - 1) > 1e-9) errors.push(`${P.id}: mixer 합 = ${s} (기대 1 ± 1e-9)`);
    } else {
      const hue = P.hue ?? [];
      if (hue.length !== 8) errors.push(`${P.id}: hue 길이 ${hue.length} (기대 8)`);
      hue.forEach((row, i) => {
        if (row.length !== 3 || row.some((v) => !Number.isFinite(v))) errors.push(`${P.id}: hue[${i}] 형식 오류`);
      });
    }
    let prevY = -Infinity;
    for (let i = 0; i <= 1023; i++) {
      const x = shaperDec(i / 1023);
      const v = renderPoint([x, x, x], P, k);
      const Y = luma709(v.map(srgbDec));
      if (Y < prevY - 1e-6) {
        errors.push(`${P.id}: 중성축 단조 위반 (i=${i}, ${prevY} → ${Y})`);
        break;
      }
      prevY = Y;
    }
  }
  if (errors.length > 0) fail("\n  " + errors.join("\n  "));
}

// ---- 3~4. 생성 ----
/** @param {import("../src/lib/color/fse/engine.mjs").FilmSim} P */
function buildLut(P) {
  const k = toneCoeffs(P.tone);
  const grid = new Float64Array(N);
  for (let i = 0; i < N; i++) grid[i] = shaperDec(i / (N - 1));
  const data = new Float64Array(N * N * N * 3);
  let o = 0;
  for (let bi = 0; bi < N; bi++) {
    for (let gi = 0; gi < N; gi++) {
      for (let ri = 0; ri < N; ri++) {
        const v = renderPoint([grid[ri], grid[gi], grid[bi]], P, k);
        for (let c = 0; c < 3; c++) {
          const x = v[c];
          if (!Number.isFinite(x) || x < 0 || x > 1) fail(`${P.id}: (${ri},${gi},${bi}) 출력 ${x} 이 [0,1] 밖이거나 유한하지 않음`);
          data[o++] = x;
        }
      }
    }
  }
  const lines = [
    `# Generated by scripts/generate-luts.mjs — FSE-v2 / ${P.id}`,
    `# INPUT: scene-linear Rec.709 D65, FSH-v1 shaper (C_S=${SHAPER_C}, X_MAX=${SHAPER_XMAX})`,
    `# OUTPUT: sRGB IEC 61966-2-1 display-encoded`,
    `TITLE "${P.en}"`,
    `LUT_3D_SIZE ${N}`,
    `DOMAIN_MIN 0.0 0.0 0.0`,
    `DOMAIN_MAX 1.0 1.0 1.0`,
  ];
  for (let i = 0; i < data.length; i += 3) {
    lines.push(`${data[i].toFixed(6)} ${data[i + 1].toFixed(6)} ${data[i + 2].toFixed(6)}`);
  }
  const cube = Buffer.from(lines.join("\n") + "\n", "utf8");
  const bin = Buffer.alloc(data.length * 2);
  for (let i = 0; i < data.length; i++) {
    bin.writeUInt16LE(Math.round(Math.min(1, Math.max(0, data[i])) * 65535), i * 2);
  }
  let min = Infinity;
  let max = -Infinity;
  for (const v of data) {
    if (v < min) min = v;
    if (v > max) max = v;
  }
  return { cube, bin, k, min, max, grey: renderPoint([0.18, 0.18, 0.18], P, k)[0] };
}

validate();

/** @type {{ path: string, buf: Buffer }[]} */
const files = [];
const sims = [];
const summary = [];
FILM_SIMS.forEach((P, order) => {
  const r = buildLut(P);
  files.push({ path: join(OUT, "cube", `${P.id}.cube`), buf: r.cube });
  files.push({ path: join(OUT, "bin", `${P.id}.bin`), buf: r.bin });
  sims.push({
    id: P.id,
    brand: P.brand,
    ko: P.ko,
    en: P.en,
    mono: P.mono,
    order,
    cube: `/luts/cube/${P.id}.cube`,
    bin: `/luts/bin/${P.id}.bin`,
    sha256Cube: sha256(r.cube),
    sha256Bin: sha256(r.bin),
    shaderHints: P.shaderHints,
  });
  summary.push({ id: P.id, b: r.k.b.toFixed(6), c: r.k.c.toFixed(6), grey018: r.grey.toFixed(4), min: r.min.toFixed(6), max: r.max.toFixed(6) });
});
const manifest = {
  schema: "fse-lut-manifest/1",
  engine: "FSE-v2",
  size: N,
  shaper: { id: "fsh-v1", c: SHAPER_C, xMax: SHAPER_XMAX },
  inputDomain: "fsh-v1-rec709-linear",
  outputDomain: "srgb-display",
  refTone: { a: REF_TONE.a, d: REF_TONE.d, hdrMax: REF_TONE.hdrMax, midOut: REF_TONE.midOut },
  sims,
};
files.push({ path: join(OUT, "manifest.json"), buf: Buffer.from(JSON.stringify(manifest, null, 2) + "\n", "utf8") });

console.table(summary);

if (CHECK) {
  /** @type {string[]} */
  const problems = [];
  for (const f of files) {
    const rel = f.path.slice(ROOT.length + 1);
    if (!existsSync(f.path)) problems.push(`누락: ${rel}`);
    else if (sha256(readFileSync(f.path)) !== sha256(f.buf)) problems.push(`sha256 불일치: ${rel}`);
  }
  if (problems.length > 0) {
    console.error(`[generate-luts --check] 실패 (${problems.length}건):\n  ${problems.join("\n  ")}\n  → npm run luts 로 재생성하세요.`);
    process.exit(1);
  }
  console.log(`[generate-luts --check] OK — ${files.length}개 파일이 재생성 결과와 일치합니다.`);
} else {
  for (const f of files) {
    mkdirSync(dirname(f.path), { recursive: true });
    writeFileSync(f.path, f.buf);
  }
  console.log(`[generate-luts] ${files.length}개 파일 작성 완료 (LUT ${FILM_SIMS.length * 2} + manifest).`);
}
